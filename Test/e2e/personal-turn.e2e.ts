import { expect, test } from '@playwright/test'

test('Auto 对话、Task 状态条、Steering 与 Follow-up 保持同一 Thread 闭环', async ({ page }) => {
  test.setTimeout(60_000)
  const suffix = Date.now().toString(36)
  const username = `turn.${suffix}`
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '登录 Oktapod' })).toBeVisible()
  await page.getByRole('tab', { name: '注册' }).click()
  await page.getByRole('textbox', { name: '用户名' }).fill(username)
  await page.getByRole('textbox', { name: '显示名称' }).fill('Turn Tester')
  await page.getByLabel('密码', { exact: true }).fill(`turn-${suffix}-password`)
  await page.getByRole('button', { name: '创建并登录' }).click()
  await expect(page.getByText('模型服务已配置')).toBeVisible()

  await page.getByRole('button', { name: '打开项目' }).click()
  await page.getByRole('textbox', { name: '项目名称' }).fill(`会话路由 ${suffix}`)
  await page.getByRole('textbox', { name: '目标说明' }).fill('验证会话优先的项目工作台')
  await page.getByRole('button', { name: '建立工作空间' }).click()

  const composerToolbar = page.locator('.conversation-composer .composer-toolbar')
  await expect(composerToolbar.getByRole('combobox', { name: '模型' })).toContainText('model-e2e')
  await expect(composerToolbar.getByRole('combobox').nth(2)).toContainText('请我审批')
  await page.getByRole('button', { name: '执行设置' }).click()
  const advancedSettings = page.locator('.composer-advanced')
  await expect(advancedSettings).toContainText('通用场景')
  await expect(advancedSettings).not.toContainText('内置执行器')
  await expect(advancedSettings.getByRole('combobox', { name: '执行 Agent' })).toHaveCount(0)
  await expect(advancedSettings).not.toContainText('项目模型')
  await expect(advancedSettings).not.toContainText('资源配额')
  await page.getByRole('button', { name: '执行设置' }).click()

  await page.getByRole('button', { name: '打开检查器' }).click()
  await page.locator('.project-management-panel > nav').getByRole('button', { name: /更多/ }).click()
  await page.locator('.panel-secondary-nav').getByRole('button', { name: '项目', exact: true }).click()
  await page.getByRole('button', { name: '项目设置' }).click()
  let projectDialog = page.getByRole('dialog')
  await expect(projectDialog.getByText('项目资源配额')).toBeVisible()
  await projectDialog.getByRole('spinbutton', { name: '项目最多模型调用' }).fill('7')
  await projectDialog.getByRole('spinbutton', { name: '项目最多 Token' }).fill('12000')
  await projectDialog.getByRole('button', { name: '保存配置' }).click()
  await page.getByRole('button', { name: '项目设置' }).click()
  projectDialog = page.getByRole('dialog')
  await expect(projectDialog.getByRole('spinbutton', { name: '项目最多模型调用' })).toHaveValue('7')
  await expect(projectDialog.getByRole('spinbutton', { name: '项目最多 Token' })).toHaveValue('12000')
  await projectDialog.getByRole('button', { name: '取消' }).click()
  await page.getByRole('button', { name: '关闭检查器' }).click()

  const composer = page.getByRole('textbox', { name: '消息' })
  await composer.fill('请直接解释 SQLite 的用途')
  await composer.press('Enter')
  await expect(page.locator('.message-thread').getByText('请直接解释 SQLite 的用途', { exact: true })).toBeVisible()
  await expect(page.locator('.thread-message.user .message-role')).toHaveText(username)
  await expect(page.locator('.thread-message.assistant .message-body').getByText('E2E 模型执行成功。', { exact: true })).toBeVisible({ timeout: 15_000 })
  await expect(page.getByRole('link', { name: /请直接解释 SQLite 的用途/ })).toBeVisible()

  await page.locator('.conversation-composer').getByRole('combobox').first().click()
  await page.getByRole('option', { name: 'Task', exact: true }).click()
  await page.getByRole('button', { name: '执行设置' }).click()
  await page.locator('.composer-advanced .inline-select').first().click()
  await page.getByRole('option', { name: '代码场景', exact: true }).click()
  const taskTitle = '受控工具审批验收：创建文件并运行 node --version'
  await composer.fill(taskTitle)
  await page.getByRole('button', { name: '发送' }).click()

  const status = page.getByRole('region', { name: '当前执行计划' })
  const statusHead = status.getByRole('button', { name: /等待你处理/ })
  await expect(statusHead).toBeVisible({ timeout: 15_000 })
  await expect(statusHead).toHaveAttribute('aria-expanded', 'true')
  await expect(status).toContainText('等待审批')

  await composer.fill('先保留已经写好的文件，只调整后续验证说明')
  await composer.press('Enter')
  await composer.fill('完成后再补一份简短变更摘要')
  await composer.press('Alt+Enter')
  await expect(status).toContainText('Steering', { timeout: 10_000 })
  await expect(status).toContainText('Follow-up')
  await expect(status.getByRole('button', { name: '撤回排队项' })).toHaveCount(2)
  await status.getByRole('button', { name: '撤回排队项' }).last().click()
  await expect(status.getByRole('button', { name: '撤回排队项' })).toHaveCount(1)
})
